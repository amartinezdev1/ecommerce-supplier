-- Run once with the database owner. Application data is not exposed through the public Data API.
CREATE SCHEMA IF NOT EXISTS rpm;
REVOKE ALL ON SCHEMA rpm FROM PUBLIC;
CREATE TABLE IF NOT EXISTS rpm.settings (
 id text PRIMARY KEY, data jsonb NOT NULL, version integer NOT NULL DEFAULT 1 CHECK(version > 0)
);
CREATE TABLE IF NOT EXISTS rpm.products (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 sku text NOT NULL UNIQUE, data jsonb NOT NULL, version integer NOT NULL DEFAULT 1 CHECK(version > 0)
);
CREATE TABLE IF NOT EXISTS rpm.members (
 email text PRIMARY KEY, role text NOT NULL CHECK(role IN ('owner','staff')),
 user_id text, active boolean NOT NULL DEFAULT true
);
CREATE TABLE IF NOT EXISTS rpm.quotes (
 id text PRIMARY KEY, owner_id text, token_hash text NOT NULL, data jsonb NOT NULL,
 status text NOT NULL DEFAULT 'solicitud', created_at timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS quotes_owner_date ON rpm.quotes(owner_id,created_at DESC);
CREATE TABLE IF NOT EXISTS rpm.audit (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor text NOT NULL, action text NOT NULL, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS rpm.auth_limits (
 key text PRIMARY KEY, attempts integer NOT NULL DEFAULT 1, expires_at timestamptz NOT NULL
);
CREATE TABLE IF NOT EXISTS rpm.owner_mappings (
 legacy_id text PRIMARY KEY, email text NOT NULL
);
